#pragma once

// ボスのフェーズ(HP の残りで決まる段階)。文字列比較ではなく enum で管理する
// (先輩フィードバックで「AI の攻撃パターン選択を文字列比較で行っている」ことが ✕ 評価の実例として挙がっていたため、この作品では避ける)。
// 分けた理由: 攻撃の表(BossAttackPlan.h)と BossComponent の両方が使うので、どちらにも依存しない小さなヘッダに置き、循環参照を避ける。
enum class BossPhase {
    Phase1, // HP 100% 〜 67%: 自機狙いの単発弾のみ
    Phase2, // HP 67% 〜 34%: 単発弾 + 扇状弾(回避を要求)
    Phase3, // HP 34% 〜 0%  : 高頻度の単発弾 + 拡大した扇状弾(弾幕)
};
