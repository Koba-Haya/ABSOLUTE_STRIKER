#pragma once
#include <cstdint>

// 1 フレームの CPU 時間を測って、平均と最大をログへ出すクラス(メインループの先頭と末尾で呼ぶ)。
//
// 分けた理由: 以前は CpuTimer の中に、ファイル内のグローバル変数として測定の状態を持っていた。
// 測定の状態(経過時間の合計・最大・フレーム数)は、メインループを持つ AbsoluteFrameWork だけが使うので、
// そのインスタンスのメンバとして持たせた(グローバル変数をなくすため)。
// 1 秒ごとに平均と最大を出し、しきい値を超えた 1 フレームはその場で出す(停止の瞬間を逃さないため)。
// 注意: 1 フレームの時間には垂直同期(60fps に合わせる待ち)も含まれるので、通常は約 16.7ms になる。
// メインスレッドからだけ呼ぶこと。
class FrameTimer {
public:
  // 1 フレームの測定の開始(メインループの先頭で呼ぶ)
  void BeginFrame();
  // 1 フレームの測定の終了(メインループの末尾で呼ぶ)。集計とログ出力を行う
  void EndFrame();

private:
  int64_t frameStartTicks_ = 0;    // 今のフレームの開始時刻(目盛り)
  int64_t intervalStartTicks_ = 0; // 今の報告間隔の開始時刻(目盛り)。0 は、まだ始まっていない
  double sumMs_ = 0.0;             // 報告間隔内の、フレーム時間の合計(ミリ秒)
  double maxMs_ = 0.0;             // 報告間隔内の、最も長かったフレーム時間(ミリ秒)
  uint32_t frames_ = 0;            // 報告間隔内の、フレーム数
};
